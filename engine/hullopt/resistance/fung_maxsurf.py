def dlr(vol_m3, L_m, rho=1025.0):
    return (rho * vol_m3 / LT_KG) / ((L_m / FT) / 100.0) ** 3

def cr(Fn, *, vol, L, Cp, AT, BT, BoT, ie, Cm, rho=1025.0, variant=0):
    D = dlr(vol, L, rho)
    lam = 0.75 * Cp + 0.035 * (0.034977 * D)   # = a1*Cp + a2*X3^2 ; validated vs Maxsurf (0.24% rms)
    Fn = np.asarray(Fn, float)
    X1 = Fn ** -0.7
    X2 = np.cos(lam * Fn ** -1.93) * np.exp(-0.2 / Fn ** 2)
    X3 = np.sqrt(0.034977 * D) * np.ones_like(Fn)
    c = lambda v: v * np.ones_like(Fn)
    X = np.stack([X1, X2, X3, c(AT), c(Cp ** 2), c(BT), c(BoT), c(math.log(90 - ie)), c(Cm)], -1)
    terms = B * np.prod(X[..., None, :] ** E, axis=-1)
    return np.exp(terms.sum(-1))

def total(kn, *, vol, L, S, Cp, AT, BT, BoT, ie, Cm, rho=1025.0, nu=1.18831e-6, CA=0.0005, cr_scale=1.0):
    v = np.asarray(kn) * 0.514444
    Fn = v / math.sqrt(9.81 * L)
    Cf = 0.075 / (np.log10(v * L / nu) - 2) ** 2
